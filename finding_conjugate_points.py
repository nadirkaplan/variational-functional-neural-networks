  #splitting the domain in half
  def domain(self, x_start, x_end, iteration):
    if iteration%2==0:
      iter = iteration/2
      mesh_sz = int(min((3**iter)*2000, 500000))
      X_f1 = np.linspace(x_start, x_end, mesh_sz).flatten()[:, None]
      x_f1 = tf.convert_to_tensor(X_f1, dtype=self.dtype)
    else:
      iter = (iteration-1)/2
      mesh_sz = int(min((3**iter)*2000, 500000))
      X_f1 = np.linspace(x_start, x_end, mesh_sz).flatten()[:, None]
      x_f1 = tf.convert_to_tensor(X_f1, dtype=self.dtype)
    return x_f1


  #defining dirichletBC as function(if bc satisfied l=0)
  def l1(self, x_f, x_end, x_start):
    return 10*(x_f-x_start)*(x_end-x_f)

  def g1(self, x_f, x_end, x_start):
    return (1/(x_start-x_end))*x_f-x_end/(x_start-x_end)        #-2*(1-np.cos(0.75*np.pi))*x_f + 1 ##generalize this for given boundary an boundary values

  def u_model_tot(self, x_f1, x_end, x_start):
    #print(x_end, x_start)
    N_phi_1 = self.u_model(x_f1)
    phi_1 = self.l1(x_f1, x_end, x_start)*N_phi_1 + self.g1(x_f1, x_end, x_start)
    return phi_1

  def rayleighian(self, x_f1, x_end, x_start):
    with tf.GradientTape(persistent=True) as tape:
      tape.watch(x_f1)

      phi_1 = self.u_model_tot(x_f1, x_end, x_start)

    phix1 = tape.gradient(phi_1, x_f1)

    del tape

    self.R1 = phix1*phix1 - (mu*mu)*phi_1*phi_1

    return tf.reduce_mean(self.R1), phi_1, phix1

  def __grad(self, x_f, x_end, x_start):
    with tf.GradientTape(persistent=True) as tape:
      loss_value1, _, _ = self.rayleighian(x_f, x_end, x_start)                             ##loss_value1 sum of rayleighian in different domains, loss_value2 smoothness
    grad = tape.gradient(loss_value1, self.__wrap_training_variables())
    del tape
    return loss_value1, grad

  def grad_flat(self, x_end, x_start, iteration):
    loss_value, grad_1 = self.__grad(x_end, x_start)
    grad_flat = []
    for i in grad_1:
      grad_flat.extend(i.numpy().flatten())

    return loss_value, tf.convert_to_tensor(grad_flat)

  def __wrap_training_variables(self):
    var = self.u_model.trainable_variables
    return var

