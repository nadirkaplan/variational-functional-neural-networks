  def finding_mult_conjugate_points(self, iterations1, tf_epochs, iterations2=100):
    x_conj_list = []
    x_bound_left = self.x_start
    for i in range(iterations2):
      x_conj = self.finding_conjugate_point(iterations1, tf_epochs, x_bound_left)
      if x_conj == None:
        break
      else:
        x_conj_list.append(x_conj)
