class VariationalFunctionalNN(object):
  def __init__(self, input_size, output_size, size_of_block, no_of_resnet_blocks, logger, X_f, x_boundary, u_boundary, approx_type="hessian"):

    input = tf.keras.Input(shape=(input_size,), name="input")
    block_output = tf.keras.layers.Dense(size_of_block, activation=tf.nn.tanh)(input)

    for i in range(no_of_resnet_blocks):
      x = tf.keras.layers.Dense(size_of_block, activation=tf.nn.tanh)(block_output)
      x = tf.keras.layers.Dense(size_of_block, activation=tf.nn.tanh)(x)
      #x = tf.keras.layers.Dense(size_of_block, activation=tf.nn.tanh)(x)
      #x = tf.keras.layers.Dense(size_of_block, activation=tf.nn.tanh)(x)
      #block_output = tf.keras.layers.add([x, block_output])

    N_phi = tf.keras.layers.Dense(output_size, name="phi", activation=None)(x)
    self.u_model = tf.keras.Model(inputs=input, outputs=N_phi)
    tf.keras.utils.plot_model(self.u_model, show_shapes=True)

    self.trainable_variables = self.u_model.trainable_variables
    self.shapes = tf.shape_n(self.trainable_variables)

    self.n_tensors = len(self.shapes)

    self.indices = []
    self.partitions = []
    count = 0

    for i, shape in enumerate(self.shapes):
      n = int(tf.reduce_prod(shape))
      self.indices.append(
          tf.reshape(tf.range(count, count + n, dtype=tf.int32), shape)
      )
      self.partitions.extend([i]*n)
      count += n

    self.total_weight_size = count
    self.logger = logger

    self.dtype = tf.float32

    self.approx_type = approx_type

    if self.approx_type == "hessian":
      self.B = tf.eye(self.total_weight_size)
    else:
      self.B_inv = tf.eye(self.total_weight_size)

    self.weights = tf.reshape(self.get_weights(), [self.total_weight_size,1])

    #Separating the collocation coordinates
    self.x_f = tf.convert_to_tensor(X_f, dtype= self.dtype)
    self.x_boundary = tf.convert_to_tensor(x_boundary, dtype=self.dtype)
    self.u_boundary = tf.convert_to_tensor(u_boundary, dtype=self.dtype)

    self.line_search_fail = 0

    self.line_search_pos = 0


  #defining dirichletBC as function(if bc satisfied l=0)
  def l(self, x_f):
    return (x_f-1)*(x_f+1.0)

  def g(self, x_f):
    return 0.0625              #-x_f + 1        #-2*(1-np.cos(0.75*np.pi))*x_f + 1

  #model including bc
  def u_model_tot(self, x_f):
    N_phi = self.u_model(x_f)
    phi = self.l(x_f)*N_phi + self.g(x_f)
    return phi     #return phi


  #rayleighian loss
  def rayleighian(self):
    with tf.GradientTape(persistent=True) as tape:
      tape.watch(self.x_f)

      phi = self.u_model_tot(self.x_f)

    phix = tape.gradient(phi, self.x_f)

    del tape

    self.R = phix*phix + (mu/2)*phi

    return tf.reduce_mean(self.R)

  def sr1_update(self, denominator, z_minus_w_dot):
    return (1/denominator)*tf.matmul(z_minus_w_dot, z_minus_w_dot, transpose_b=True)


  @tf.function
  def grad(self):
    with tf.GradientTape() as tape:
      loss_value = self.rayleighian()                             ##self.loss_tot()
    return loss_value, tape.gradient(loss_value, self.trainable_variables)

  @tf.function
  def grad_flat(self):
    loss_value, grad_1 = self.grad()
    grad_flat = tf.dynamic_stitch(self.indices, grad_1)
    grad_flat = tf.reshape(grad_flat, shape=[self.total_weight_size,1])

    return loss_value, grad_flat


  def __wrap_training_variables(self):
    var = self.u_model.trainable_variables
    return var

  #get flat weights from u_model
  def get_weights(self):
    return tf.dynamic_stitch(self.indices, self.u_model.trainable_variables)


  #apply weights calculated from get_weights to another u_model?
  def set_weights(self, w):
    weights = tf.dynamic_partition(w, self.partitions, self.n_tensors)
    for i, (shape, param) in enumerate(zip(self.shapes, weights)):
      self.trainable_variables[i].assign(tf.reshape(param, shape))

  def summary(self):
    return self.u_model.summary()


  def sr1_update(self, denominator, z_minus_w_dot):
    return (1/denominator)*tf.matmul(z_minus_w_dot, z_minus_w_dot, transpose_b=True)

  def dot(self, p):
    if self.approx_type == "hessian":
      return tf.linalg.matmul(self.B, p)
    else:
      return tf.linalg.matmul(self.B_inv, p)

  def sr1_hessian_update(self, delta_weights, delta_g, epsilon=1e-6):                             #delta_g = difference between successive gradients, delta_x = difeerence between successive x
    if self.approx_type == "hessian":
      w = delta_weights
      z = delta_g
    else:
      w = delta_g
      z = delta_weights

    w_dot = self.dot(w)
    z_minus_w_dot = z - w_dot
    denominator = tf.reduce_sum(w*z_minus_w_dot)
    if tf.abs(denominator) <= epsilon*tf.norm(w)*tf.norm(z_minus_w_dot):
      print('update not happening')
      return
    #update matrix
    if self.approx_type == "hessian":
      self.B += self.sr1_update(denominator, z_minus_w_dot)
    else:
      self.B_inv += self.sr1_update(denominator, z_minus_w_dot)

  #including line-search routine
  def get_gradient_line_search_n(self,x):
    self.set_weights(x)
    _, grads = self.grad_flat()
    return grads       #.numpy().flatten()

  def function_line_search_n(self,x):
    self.set_weights(x)
    loss = self.rayleighian()
    return loss                  #.numpy()

  def get_gradient_line_search_p(self,x): ### new linesearch function when del_f_kT*p_k > 0
    self.set_weights(x)
    _, grads = self.grad_flat()
    return -grads.numpy().flatten()

  def function_line_search_p(self,x):
    self.set_weights(x)
    loss = self.rayleighian()
    return -loss.numpy()

  def line_search_mod_wolfe(self):
    _, g_k = self.grad_flat()
    p_k = -tf.matmul(self.B_inv,g_k)
    p_k_ls = p_k.numpy().flatten()
    x_k_ls = self.weights.numpy().flatten()
    if tf.reduce_sum(g_k*p_k) <= 0:
      return sp.optimize.line_search(self.function_line_search_n, self.get_gradient_line_search_n, x_k_ls, p_k_ls, amax=1, maxiter=100, c2=1e-3, c1=1e-7)[0]
    else:
      return sp.optimize.line_search(self.function_line_search_p, self.get_gradient_line_search_p, x_k_ls, p_k_ls, amax=1, maxiter=100, c2=1e-3, c1=1e-7)[0]

  def line_search_crude(self, beta):
    _, g_k = self.grad_flat()
    p_k = -tf.matmul(self.B_inv,g_k)
    p_k_ls = p_k.numpy().flatten()
    x_k_ls = self.weights.numpy().flatten()
    alpha = 1
    alpha_star = 0
    #beta_0 = 1

    def derphi(alpha):
      return tf.reduce_mean(tf.square(self.get_gradient_line_search_n(x_k_ls + alpha*p_k_ls)))   #why consider the component along p_k? why not try to just look for norm of grad

    derphi_0 = abs(derphi(0))            #remove abs operator
    #print('derphi(0)=',derphi_0)
    #_, grad_flat = self.grad_flat()
    #print('grad_mag',tf.reduce_mean(tf.square(grad_flat)))

    for i in range(50):
      #beta = beta_0*(i+1)
      grad_diff = abs(derphi(alpha))-derphi_0
      if generator.uniform(shape=[1], minval=0.0, maxval=1.0) <= tf.exp(-(beta/tf.pow(derphi_0,0.5))*(grad_diff)):          #included coupling between grad and temp  #(abs(derphi(alpha)/derphi(0)))
        alpha_star = alpha
        break
      else:
        alpha = 0.9*alpha

    if alpha_star == 0:
      self.line_search_fail += 1
      #print("line search failed")
      return 0.001
    else:
      if grad_diff.numpy()>=0:
        self.line_search_pos += 1
      return alpha_star



  def update_delta_weights_delta_g_newton(self, beta):
    grads = self.grad_flat()[1]
    lr = self.line_search_crude(beta)
    weights_new = self.weights - lr*tf.matmul(self.B_inv,grads)
    delta_weights = weights_new-self.weights
    self.weights = weights_new
    self.set_weights(tf.reshape(self.weights,[-1]))
    loss, grads_new = self.grad_flat()
    delta_g = grads_new-grads
    return loss, delta_weights, delta_g, grads                              #carry forward the loss

  def update_delta_weights_delta_g_newton_const_lr(self, lr):
    grads = self.grad_flat()[1]
    weights_new = self.weights - lr*tf.matmul(self.B_inv,grads)
    delta_weights = weights_new-self.weights
    self.weights = weights_new
    self.set_weights(tf.reshape(self.weights,[-1]))
    loss, grads_new = self.grad_flat()
    delta_g = grads_new-grads
    return loss, delta_weights, delta_g

  def sr1_optimize_const_lr(self, lr, iter=100):
    self.logger.log_train_start(self)
    self.logger.log_train_opt("SR1_quasi_newton_const_lr")
    for i in range(iter):
      loss, delta_weights, delta_g = self.update_delta_weights_delta_g_newton_const_lr(lr=lr)  #input velocity=velocity
      self.sr1_hessian_update(delta_weights, delta_g)
      self.logger.log_train_epoch(i, loss)

  def sr1_optimize_line_search(self, iter=100):
    self.logger.log_train_opt("SR1_quasi_newton_line_search")
    for i in range(100):
      loss, delta_weights, delta_g = self.update_delta_weights_delta_g_newton_const_lr(lr = 1e-5)  #input velocity=velocity
      self.sr1_hessian_update(delta_weights, delta_g)
    for i in range(iter):
      beta_0 = 0.1
      epsilon = 0.001
      temp = (1.0-epsilon)*np.exp(-0.01*i)+epsilon
      beta = 1/temp #min(beta_0*(0.01*i+10),100.0)
      #print(beta)
      loss, delta_weights, delta_g, grads = self.update_delta_weights_delta_g_newton(beta)
      grad_mg = tf.reduce_mean(tf.square(grads))
      #print('grad_mag=',grad_mg.numpy())
      if grad_mg <= 1e-10:              #reached 1e-4 9 out of 10 times
        return i
        #print('tol reached')
        #break
      self.sr1_hessian_update(delta_weights, delta_g)
      self.logger.log_train_epoch(i, loss, custom=f"line_search_fail={self.line_search_fail}")


  def predict(self, X_star):
    phi = self.u_model_tot(X_star)
    return phi

