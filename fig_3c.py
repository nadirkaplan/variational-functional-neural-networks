  def log_train_opt(self, name):
    print(f"-- Starting {name} optimization --")

  def log_train_end(self, epoch, custom=""):
    print("===============")
    print(f"Training finished (epoch {epoch}): duration = {self.__get_elapsed()} " + custom)

